// =============================================================================
// tray.rs — 系统托盘：图标、右键菜单、双击事件
// =============================================================================
//
// 系统托盘是桌面应用中常见的功能：
// - 应用关闭后仍在任务栏右下角显示小图标
// - 右键图标可以弹出菜单（显示窗口、退出等）
// - 双击图标可以恢复窗口
//
// 关键概念：
// - TrayIconBuilder: 用于构建托盘图标的建造者模式
// - MenuItem: 菜单项，通过 ID 标识
// - Menu: 菜单容器，可以包含多个 MenuItem
// - on_menu_event: 菜单项被点击时的回调
// - on_tray_icon_event: 托盘图标本身的事件（单击、双击等）

use tauri::{
    menu::{Menu, MenuItem},   // 菜单相关类型
    tray::TrayIconBuilder,     // 托盘图标建造者
    App, Manager,              // App 代表应用实例，Manager 提供 get_webview_window 等方法
};

/// 创建系统托盘图标和菜单
///
/// # 返回值
/// - `Ok(TrayIcon)`: 成功创建的托盘图标
/// - `Err`: 创建失败时的错误信息
///
/// # 托盘菜单结构
/// ```
/// ┌─────────────┐
/// │  显示窗口    │  ← 点击后显示并聚焦主窗口
/// │  退出        │  ← 点击后完全退出应用
/// └─────────────┘
/// ```
pub fn create_tray(app: &App) -> Result<tauri::tray::TrayIcon, Box<dyn std::error::Error>> {
    // -------------------------------------------------------------------------
    // 创建菜单项
    // -------------------------------------------------------------------------
    // MenuItem::with_id 参数说明：
    // - 第 1 个: app 引用
    // - 第 2 个: 唯一 ID（字符串），用于在事件回调中识别是哪个菜单项被点击
    // - 第 3 个: 显示文本
    // - 第 4 个: 是否启用（false = 灰色不可点击）
    // - 第 5 个: 快捷键（None 表示无快捷键）
    let show = MenuItem::with_id(app, "show", "显示窗口", true, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", "退出", true, None::<&str>)?;

    // -------------------------------------------------------------------------
    // 创建菜单容器
    // -------------------------------------------------------------------------
    // Menu::with_items 将多个 MenuItem 组合成一个菜单
    let menu = Menu::with_items(app, &[&show, &quit])?;

    // -------------------------------------------------------------------------
    // 构建托盘图标
    // -------------------------------------------------------------------------
    let tray = TrayIconBuilder::new()
        // 设置右键菜单
        .menu(&menu)
        // 鼠标悬停时显示的提示文字
        .tooltip("Test WebView")
        // -------------------------------------------------------------------------
        // 菜单事件回调：当用户点击托盘菜单中的某个项时触发
        // -------------------------------------------------------------------------
        .on_menu_event(|app, event| match event.id.as_ref() {
            // 点击"显示窗口"：显示主窗口并聚焦
            "show" => {
                // get_webview_window("main") 获取名为 "main" 的窗口
                // 窗口名在 tauri.conf.json 中定义
                if let Some(window) = app.get_webview_window("main") {
                    let _ = window.show();    // 显示窗口
                    let _ = window.set_focus(); // 将窗口带到前台并聚焦
                }
            }
            // 点击"退出"：完全退出应用
            "quit" => {
                app.exit(0); // 退出码 0 表示正常退出
            }
            _ => {}
        })
        // -------------------------------------------------------------------------
        // 托盘图标事件回调：当用户与托盘图标本身交互时触发
        // -------------------------------------------------------------------------
        .on_tray_icon_event(|tray, event| {
            // 处理双击事件：双击托盘图标恢复窗口
            if let tauri::tray::TrayIconEvent::DoubleClick { .. } = event {
                let app = tray.app_handle();
                if let Some(window) = app.get_webview_window("main") {
                    let _ = window.show();
                    let _ = window.set_focus();
                }
            }
        })
        // 构建并返回托盘图标实例
        .build(app)?;

    Ok(tray)
}
